import threading

# 支持的语言（key, 下拉显示名）：显示名永远用该语言自己的写法，
# 让用户在陌生界面语言下也认得出自己的语言。
LANGS = (
    ("zh-Hans", "简体中文"),
    ("zh-Hant", "繁體中文"),
    ("en", "English"),
    ("ru", "Русский"),
    ("fr", "Français"),
    ("de", "Deutsch"),
)
_LANG_KEYS = frozenset(k for k, _n in LANGS)
DEFAULT = "zh-Hans"

_lock = threading.Lock()
_lang = None  # 进程内缓存：None = 下次取时读盘


def reset_cache():
    """写盘切换语言后调用：让下一次 t() 重新读配置。"""
    global _lang
    with _lock:
        _lang = None


def current_lang():
    """当前语言：读配置 `lang` 键，缺省/非法值回 zh-Hans（带进程内缓存）。"""
    global _lang
    if _lang is None:
        with _lock:
            # 二次检查后直接赋值：这里不能再套一层 with _lock（普通锁不可重入，
            # 嵌套会自锁死——单测当场挂过）
            if _lang is None:
                lang = None
                try:
                    from peasebar import sections
                    lang = sections.load_config().get("lang")
                except Exception:  # noqa: BLE001  读盘失败不弄崩渲染
                    lang = None
                _lang = lang if lang in _LANG_KEYS else DEFAULT
    return _lang


def set_lang(lang):
    """切换语言并写盘（设置窗重建与菜单刷新由调用方触发）。"""
    if lang not in _LANG_KEYS:
        return False
    from peasebar import sections
    cfg = sections.load_config()
    cfg["lang"] = lang
    sections.save_config(cfg)
    reset_cache()
    return True


def t(key, **kw):
    """取词条：当前语言 → zh-Hans 回退 → 键名兜底；占位符 str.format。"""
    lang = current_lang()
    table = _STRINGS.get(lang) or {}
    s = table.get(key)
    if s is None:
        s = _STRINGS[DEFAULT].get(key, key)
    if kw:
        try:
            s = s.format(**kw)
        except Exception:  # noqa: BLE001  文案含字面花括号时按原样返回
            pass
    return s


def lang_names():
    """语言下拉用：[(key, 自称名), …]（保持 LANGS 顺序，简中排首=默认）。"""
    return list(LANGS)


