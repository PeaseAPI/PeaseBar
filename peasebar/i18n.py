"""多语言框架（2026-11-24 用户需求：默认简中，可切英/俄/法/德/繁中）。

- 语言存配置 `lang` 键（sections.load_config 读），缺省 zh-Hans；
- `t(key, **kw)` 取当前语言词条，缺键回退 zh-Hans，再缺回键名本身
  （开发期一眼看出漏译，不会把 KeyError 砸到渲染路径上）；
- 词条表是纯 dict：键为语义键（`page.layout`、`opt.real_bar.tip`），
  占位符用 str.format（`{n}`、`{sec}`），文案里出现字面花括号时 format
  失败会被 t() 吞掉按原样返回（安全网）；
- 语言缓存进程内一份，`reset_cache()` 在写盘切换语言后调用（设置窗
  _rebuild 与控制图标菜单刷新都靠它拿到新语言）。

注释语言规范：本项目注释一律中文（无论界面语言切到哪）。
"""
import os
